mod backup;
mod docker;
mod scheduler;
mod system;
mod texts;

use clap::{CommandFactory, FromArgMatches, Parser, Subcommand};

pub use backup::{
    BackupCommand, BackupConfigCommand, CreateParameters, HealthCommand, HealthReportCommand,
};
pub use docker::{ContainerCommand, ContainersCommand, DockerCommand};
pub use scheduler::{AddParameters, SchedulerCommand};
pub use system::SystemCommand;

#[derive(Debug, Parser, PartialEq, Eq)]
#[command(name = "kida", version, about = texts::ABOUT)]
pub struct Cli {
    #[command(subcommand)]
    pub command: Command,
}

impl Cli {
    pub fn parse_with_help() -> Self {
        let matches = with_banner(Self::command()).get_matches();
        Self::from_arg_matches(&matches).unwrap_or_else(|error| error.exit())
    }
}

fn with_banner(mut command: clap::Command) -> clap::Command {
    fn apply(command: clap::Command) -> clap::Command {
        command.before_help(texts::BANNER).mut_subcommands(apply)
    }

    // Include the help subcommands generated by Clap.
    command.build();
    apply(command)
}

#[derive(Debug, Subcommand, PartialEq, Eq)]
pub enum Command {
    Scheduler {
        #[command(subcommand)]
        command: SchedulerCommand,
    },
    System {
        #[command(subcommand)]
        command: SystemCommand,
    },
    Docker {
        #[command(subcommand)]
        command: DockerCommand,
    },
    Backup {
        #[command(subcommand)]
        command: BackupCommand,
    },
}

